#!/usr/bin/env bash
set -euo pipefail
[[ $# -eq 2 || $# -eq 3 ]] || { echo "usage: $0 TASK WORKSPACE [TRANSCRIPT]" >&2; exit 2; }
task="$1"
ws="$2"
transcript="${3:-}"
status=fail
reason=''
case "$task" in
  exact_contract)
    if [[ -z "$transcript" ]]; then
      status=manual
      reason='provide transcript.txt for mechanical scoring'
    elif [[ ! -f "$transcript" ]]; then
      reason='transcript does not exist'
    else
      expected='{"status":"ready","values":[3,8,13],"sum":24}'
      # ponytail: the echoed prompt is the first match; the second is the
      # assistant response. Parse the terminal protocol if UI redraws change.
      matches="$(strings -n 4 -- "$transcript" | rg -F -c -- "$expected" || true)"
      matches="${matches:-0}"
      if (( matches >= 2 )); then
        status=pass
        reason='expected JSON appears in prompt echo and captured response'
      else
        reason="expected JSON response not captured (matches=$matches)"
      fi
    fi
    ;;
  code_scope)
    if (cd "$ws" && python -m unittest discover -s tests -v >/tmp/eval-flash-score.log 2>&1) && [[ "$(git -C "$ws" status --short --untracked-files=all | sed '/__pycache__\//d;/\.pyc$/d')" == ' M calculator.py' ]]; then
      status=pass
      reason='tests pass and only calculator.py changed (generated bytecode ignored)'
    else
      reason="tests or scope failed: $(git -C "$ws" status --short --untracked-files=all | sed '/__pycache__\//d;/\.pyc$/d')"
    fi
    ;;
  long_context)
    if [[ -f "$ws/answer.json" ]] && jq -e '. == {project_code:"Aster-17",launch_day:"Thursday",retention_days:28,owner:"Nilo",support_tier:"NOT_FOUND"}' "$ws/answer.json" >/dev/null && [[ "$(git -C "$ws" status --short --untracked-files=all)" == '?? answer.json' ]]; then
      status=pass
      reason='exact answer.json and no forbidden edits'
    else
      reason='answer or scope failed'
    fi
    ;;
  tool_sequence)
    if [[ -f "$ws/answer.json" ]] && jq -e '. == {completed_count:3,completed_owners:["aisha","mika","zara"],highest_priority_open:"evt-104"}' "$ws/answer.json" >/dev/null && [[ "$(git -C "$ws" status --short --untracked-files=all)" == '?? answer.json' ]]; then
      status=pass
      reason='exact answer.json and no forbidden edits'
    else
      reason='answer or scope failed'
    fi
    ;;
  *) echo "unknown task $task" >&2; exit 2 ;;
esac
jq -n --arg task "$task" --arg status "$status" --arg reason "$reason" '{task:$task,status:$status,reason:$reason}'
[[ "$status" == pass || "$status" == manual ]]
